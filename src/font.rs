pub struct Glyph {
    pub rows: [u8; 8],
    pub width: i32,
}

pub struct Font {
    table: Vec<Option<Glyph>>, // indexed by ascii code
}

impl Font {
    pub fn new() -> Font {
        let mut table: Vec<Option<Glyph>> = (0..128).map(|_| None).collect();
        for (ch, rows) in GLYPHS {
            let mut bits = [0u8; 8];
            let mut width = 1;
            for (r, row) in rows.iter().enumerate() {
                for (c, b) in row.chars().enumerate() {
                    if b == '#' {
                        bits[r] |= 1 << c;
                        width = width.max(c as i32 + 1);
                    }
                }
            }
            table[*ch as usize] = Some(Glyph { rows: bits, width });
        }
        Font { table }
    }

    pub fn glyph(&self, c: char) -> Option<&Glyph> {
        let i = c as usize;
        if i < 128 {
            self.table[i].as_ref()
        } else {
            None
        }
    }

    /// Advance in font pixels (glyph width + 1 spacing).
    pub fn advance(&self, c: char) -> i32 {
        match c {
            ' ' => 3,
            _ => self.glyph(c).or_else(|| self.glyph('?')).map(|g| g.width + 1).unwrap_or(4),
        }
    }

    pub fn width(&self, s: &str) -> i32 {
        let w: i32 = s.chars().map(|c| self.advance(c)).sum();
        (w - 1).max(0)
    }

    /// Calls `f(x, y)` for every lit pixel of the string (font pixel units).
    #[allow(dead_code)]
    pub fn for_each_pixel(&self, s: &str, mut f: impl FnMut(i32, i32)) {
        let mut x = 0;
        for c in s.chars() {
            if c != ' ' {
                let g = self.glyph(c).or_else(|| self.glyph('?'));
                if let Some(g) = g {
                    for (r, bits) in g.rows.iter().enumerate() {
                        for col in 0..5 {
                            if bits & (1 << col) != 0 {
                                f(x + col, r as i32);
                            }
                        }
                    }
                }
            }
            x += self.advance(c);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn every_printable_ascii_has_a_glyph() {
        let f = Font::new();
        for c in 33u8..127 {
            let ch = c as char;
            if ch == '`' || ch == '{' || ch == '}' {
                continue;
            }
            assert!(f.glyph(ch).is_some(), "missing glyph for {:?}", ch);
        }
        assert!(f.width("iii") < f.width("WWW"), "font is proportional");
    }
}
